// ============================================================================
// GENERATES supabase/seed.sql AND supabase/setup.sql FROM src/lib/defaults.js
// Run with: npm run build:sql
// ============================================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defaultContent, defaultCollections, defaultSubmissions } from '../src/lib/defaults.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const supabaseDir = path.join(rootDir, 'supabase');

function sqlJsonLiteral(obj) {
  const raw = JSON.stringify(obj).replace(/'/g, "''");
  return `'${raw}'::jsonb`;
}

const seedLines = [
  '-- ============================================================================',
  '-- VERDANTRA — GENERATED DEMO SEED SQL (DO NOT EDIT MANUALLY)',
  '-- Generated by scripts/build-sql.mjs from src/lib/defaults.js',
  '-- Safe to re-run: only populates empty tables and missing content keys.',
  '-- ============================================================================',
  ''
];

// 1. Seed site_content sections
seedLines.push('-- 1. Page Sections (site_content)');
for (const [key, data] of Object.entries(defaultContent)) {
  const safeKey = key.replace(/'/g, "''");
  seedLines.push(
    `insert into public.site_content (key, data) values ('${safeKey}', ${sqlJsonLiteral(data)}) on conflict (key) do nothing;`
  );
}
seedLines.push('');

// 2. Seed collections using jsonb_populate_recordset(...) where not exists (...)
const collectionColumns = {
  initiatives: ['sort_order', 'published', 'title', 'slug', 'tags', 'highlight_tag', 'event_date', 'location', 'participants_goal', 'image', 'summary'],
  problems: ['sort_order', 'published', 'featured', 'title', 'slug', 'badge_1', 'badge_2', 'severity', 'metric_value', 'metric_label', 'image', 'summary', 'full_analysis', 'solution_steps'],
  projects: ['sort_order', 'published', 'featured', 'title', 'slug', 'category', 'status', 'location', 'completion_pct', 'hectares_restored', 'published_date', 'image', 'summary', 'body'],
  stats: ['sort_order', 'published', 'value', 'suffix', 'label', 'detail'],
  team: ['sort_order', 'published', 'name', 'role', 'location', 'image', 'bio'],
  tiers: ['sort_order', 'published', 'featured', 'name', 'amount', 'frequency', 'impact_metric', 'perks'],
  testimonials: ['sort_order', 'published', 'quote', 'author', 'role', 'avatar'],
  faqs: ['sort_order', 'published', 'category', 'question', 'answer'],
  partners: ['sort_order', 'published', 'name', 'region', 'url']
};

seedLines.push('-- 2. Collections');
for (const [table, rows] of Object.entries(defaultCollections)) {
  const cols = collectionColumns[table];
  if (!cols || !rows?.length) continue;
  const cleanRows = rows.map((r) => {
    const o = {};
    cols.forEach((c) => {
      o[c] = r[c];
    });
    return o;
  });
  const colList = cols.join(', ');
  seedLines.push(
    `insert into public.${table} (${colList})`,
    `select ${colList}`,
    `from jsonb_populate_recordset(null::public.${table}, ${sqlJsonLiteral(cleanRows)})`,
    `where not exists (select 1 from public.${table});`,
    ''
  );
}

// 3. Seed sample submissions
const submissionColumns = {
  messages: ['name', 'email', 'phone', 'subject', 'message', 'status', 'created_at'],
  donations: ['donor_name', 'email', 'amount', 'frequency', 'tier_name', 'focus_area', 'notes', 'status', 'created_at'],
  volunteers: ['full_name', 'email', 'phone', 'initiative', 'availability', 'skills', 'status', 'created_at'],
  subscribers: ['email', 'source', 'status', 'created_at']
};

seedLines.push('-- 3. Sample Inbox Submissions');
for (const [table, rows] of Object.entries(defaultSubmissions)) {
  const cols = submissionColumns[table];
  if (!cols || !rows?.length) continue;
  const cleanRows = rows.map((r) => {
    const o = {};
    cols.forEach((c) => {
      o[c] = r[c];
    });
    return o;
  });
  const colList = cols.join(', ');
  seedLines.push(
    `insert into public.${table} (${colList})`,
    `select ${colList}`,
    `from jsonb_populate_recordset(null::public.${table}, ${sqlJsonLiteral(cleanRows)})`,
    `where not exists (select 1 from public.${table});`,
    ''
  );
}

const seedSql = seedLines.join('\n');
const schemaSql = fs.readFileSync(path.join(supabaseDir, 'schema.sql'), 'utf-8');
const setupSql = `${schemaSql}\n\n${seedSql}`;

fs.writeFileSync(path.join(supabaseDir, 'seed.sql'), seedSql, 'utf-8');
fs.writeFileSync(path.join(supabaseDir, 'setup.sql'), setupSql, 'utf-8');

console.log('Generated supabase/seed.sql and supabase/setup.sql successfully.');
